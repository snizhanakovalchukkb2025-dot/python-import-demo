# lib.py - Модуль із математичними функціями

def multiply(a, b):
    """Повертає добуток двох чисел."""
    return a * b


def power(base, exponent):
    """Підносить число base до степеня exponent."""
    return base ** exponent


def subtract(a, b):
    """Повертає різницю двох чисел (a - b)."""
    return a - b